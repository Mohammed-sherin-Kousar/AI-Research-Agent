"""**CREATING SEACH TOOL**"""

@tool
def search(topic: str):
    """
    Search the mock knowledge base for the given topic.
    """

    for _, row in knowledge_df.iterrows():

        if topic.lower() in row["keyword"].lower():

            return {
                "information": row["snippet"],
                "source": row["source"]
            }

    return {
        "information": "No information found.",
        "source": "N/A"
    }

print(search.invoke({"topic":"ethical AI"}))

"""**CREATING SUMMARIZATION TOOL**"""

@tool
def summarize(text:str)->str:
  """Summarize the search results"""

  message = HumanMessage(
        content=f"""

    Summarize the following information.

{text}

    Give the output in this format:

    topic:

    Summary:

    Key Points:


    """
        )

  response = llm.invoke([message])

  return response.content

topic = "large language models ChatGPT"

search_result = search.invoke({"topic": topic})

summary = summarize.invoke({"text": search_result["information"]})

print(summary)

print("\nSource:",search_result["source"])

