"""**CREATING A SAVE REPORT TOOL**"""

@tool
def save_report(topic: str, report: str):
    """Saves the generated report to a markdown file."""

    import os

    os.makedirs("output", exist_ok=True)

    filepath = f"output/{topic.replace(' ', '_')}.md"

    with open(filepath, "w", encoding="utf-8") as file:
        file.write(report)

    return filepath

file_path = save_report.invoke({"topic": topic, "report": summary})

print(f"Report saved to {file_path}")

"""**BINDING TOOLS**

TOPIC-"climate agriculture"
"""

llm_with_tools = llm.bind_tools([search,summarize,save_report])

topic = "climate agriculture"
message = HumanMessage(
    content = f"Generate a research report on {topic}"
)

response = llm_with_tools.invoke([message])

print(response.tool_calls)

tool_name = response.tool_calls[0]["name"]

tool_args = response.tool_calls[0]["args"]

if tool_name == "search":

    search_result = search.invoke(tool_args)

    print(search_result)

summary = summarize.invoke({"text": search_result["information"]})

print(summary)
print("\nSources:",search_result["source"])

report = summary + "\n\nSources:\n" + search_result["source"]

file_path = save_report.invoke({"topic":topic,"report":report})
print(file_path)

print("Research Report Generated Successfully")
print("Saved at:", file_path)

